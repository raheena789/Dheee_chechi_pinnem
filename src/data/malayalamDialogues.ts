export function getMalayalamDialogue(count: number): MalayalamDialogue {
  // Find best matching dialogue for current count
  const sorted = [...MALAYALAM_DIALOGUES].sort((a, b) => b.minCount - a.minCount);
  const match = sorted.find(d => count >= d.minCount);
  return match || MALAYALAM_DIALOGUES[0];
}

/**
 * Phonetic pronunciation text for speech synthesis if Malayalam voices are unavailable
 */
export function getPhoneticSpeechText(dialogue: MalayalamDialogue): string {
  // If the browser speaks English, reading Malayalam script directly may be silent or broken.
  // We provide the English transliteration with Malayalam flavor so speech synthesis pronounces it humorously!
  return dialogue.transliteration;
}
